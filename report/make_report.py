def set_run(run, size=14, bold=False, font=BODY_FONT, color=None):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = font
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:ascii"), font)
    rFonts.set(qn("w:hAnsi"), font)
    rFonts.set(qn("w:cs"), BODY_FONT)
    rFonts.set(qn("w:eastAsia"), font)
    if rPr.find(qn("w:bidi")) is None:
        rPr.append(OxmlElement("w:bidi"))
    if color:
        run.font.color.rgb = RGBColor(*color)


def _bidi_p(p):
    pPr = p._p.get_or_add_pPr()
    if pPr.find(qn("w:bidi")) is None:
        pPr.append(OxmlElement("w:bidi"))
    jc = pPr.find(qn("w:jc"))
    if jc is None:
        jc = OxmlElement("w:jc")
        pPr.append(jc)
    return p


def para(text, size=13, bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
         space_after=8, line=1.35, indent=True, font=BODY_FONT, space_before=0):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = align
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    pf.line_spacing = line
    if indent:
        pf.first_line_indent = Cm(1.0)
    else:
        pf.first_line_indent = Cm(0)
    _bidi_p(p)
    r = p.add_run(text)
    set_run(r, size, bold, font)
    return p


def h1(text):
    p = para(text, size=17, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER,
             space_after=16, space_before=6, indent=False)
    return p


def h2(text):
    return para(text, size=14.5, bold=True, align=WD_ALIGN_PARAGRAPH.RIGHT,
                space_after=10, space_before=12, indent=False)


def h3(text):
    return para(text, size=13, bold=True, align=WD_ALIGN_PARAGRAPH.RIGHT,
                space_after=8, space_before=8, indent=False)


def bullet(text, size=13):
    p = para("•  " + text, size=size, indent=False, space_after=4)
    p.paragraph_format.left_indent = Cm(0.7)
    return p


def cap(text):
    return para(text, size=11, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER,
                space_after=10, space_before=4, indent=False)


def figure(img, caption, width_cm=15):
    p = doc.add_paragraph()
    p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(2)
    _bidi_p(p)
    run = p.add_run()
    run.add_picture(os.path.join(FIG, img), width=Cm(width_cm))
    cap(caption)


def shade(cell, color="D9F1ED"):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), color)
    tcPr.append(shd)


def table(headers, rows, widths=None, font_size=11, caption=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        _bidi_p(p)
        r = p.add_run(htxt)
        set_run(r, font_size, bold=True)
        shade(hdr[i])
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            _bidi_p(p)
            r = p.add_run(str(val))
            set_run(r, font_size, bold=False)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    if caption:
        cap(caption)
    else:
        sp = doc.add_paragraph()
        sp.paragraph_format.space_after = Pt(2)
    return t


